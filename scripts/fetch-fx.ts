// Fetch ECB euro reference exchange rates (annual averages) into data/fx/ecb.yaml.
// Used only to show costs in EUR next to the original figure; the original stays the sourced value.
// The current year has no annual average yet: it gets the average of the months published so far, marked partial.
//   npm run fetch:fx
import { mkdirSync, writeFileSync } from 'node:fs';
import { stringify } from 'yaml';

const CURRENCIES = ['USD', 'GBP', 'JPY', 'KRW', 'AUD', 'CZK', 'PLN', 'SEK', 'NOK', 'DKK', 'CHF', 'CAD', 'TRY', 'INR', 'CNY', 'RUB', 'ILS', 'HUF', 'RON'];
const BASE = 'https://data-api.ecb.europa.eu/service/data/EXR';
const today = new Date().toISOString().slice(0, 10);
const year = new Date().getUTCFullYear();

async function csv(url: string): Promise<Record<string, string>[]> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  const [head, ...lines] = (await res.text()).trim().split('\n');
  const cols = head.split(',');
  return lines.map((l) => Object.fromEntries(l.split(',').map((v, i) => [cols[i], v])));
}

const annualUrl = `${BASE}/A.${CURRENCIES.join('+')}.EUR.SP00.A?format=csvdata&startPeriod=2000`;
const monthlyUrl = `${BASE}/M.${CURRENCIES.join('+')}.EUR.SP00.A?format=csvdata&startPeriod=${year}-01`;
const annual = await csv(annualUrl);
const monthly = await csv(monthlyUrl);

const rates: Record<string, Record<number, number>> = {};
for (const r of annual) (rates[r.CURRENCY] ??= {})[Number(r.TIME_PERIOD)] = Number(Number(r.OBS_VALUE).toFixed(6));
const partial: Record<string, { value: number; months: string }> = {};
for (const c of CURRENCIES) {
  if (rates[c]?.[year]) continue;
  const ms = monthly.filter((r) => r.CURRENCY === c).sort((a, b) => a.TIME_PERIOD.localeCompare(b.TIME_PERIOD));
  if (!ms.length) continue;
  partial[c] = {
    value: Number((ms.reduce((s, r) => s + Number(r.OBS_VALUE), 0) / ms.length).toFixed(6)),
    months: `${ms[0].TIME_PERIOD} to ${ms[ms.length - 1].TIME_PERIOD}`,
  };
}

mkdirSync('data/fx', { recursive: true });
writeFileSync(
  'data/fx/ecb.yaml',
  `# Generated by scripts/fetch-fx.ts on ${today}. Units of foreign currency per 1 EUR.\n` +
    stringify(
      {
        source: {
          id: 'ecb-exr',
          url: annualUrl,
          title: 'Euro foreign exchange reference rates, annual averages (EXR)',
          publisher: 'European Central Bank',
          retrieved: today,
          kind: 'government',
        },
        annual: rates,
        partial_year: { year, rates: partial },
      },
      { lineWidth: 0 },
    ),
);
console.log(`fx: ${Object.keys(rates).length} currencies, ${annual.length} annual rates, partial ${year}: ${Object.keys(partial).join(', ') || 'none'}`);
